private void loadData() {

    if (house == null) {
        return;
    }

    lblName.setText(
            house.getName()
    );

    lblLocation.setText(
            house.getLocation()
    );

    lblPrice.setText(
            "Rs. " + house.getPrice() + "/month"
    );

    loadImage();
}
    private void loadImage() {
 
        try {
 
            String imagePath = house.getImage();
 
            if (imagePath == null || imagePath.isEmpty()) {
 
                lblImage.setText("No Image");
 
                return;
            }
 
            ImageIcon icon =
                    new ImageIcon(imagePath);
 
            Image scaledImage =
                    icon.getImage().getScaledInstance(
                            260,
                            170,
                            Image.SCALE_SMOOTH
                    );
 
            lblImage.setIcon(
                    new ImageIcon(scaledImage)
            );
 
            lblImage.setText("");
 
        } catch (Exception e) {
 
            lblImage.setText("No Image");
 
            e.printStackTrace();
        }
    }
 
