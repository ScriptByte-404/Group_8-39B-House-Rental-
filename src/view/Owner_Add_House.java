    /**
     * @param args the command line arguments
     */
 public static void main(String args[]) {
 
    java.awt.EventQueue.invokeLater(() -> {
        // Fetch a real user from DB for standalone testing so owner_id FK is valid
        if (util.SessionManager.getCurrentUser() == null) {
            try {
                database.MysqlConnector connector = new database.MysqlConnector();
                java.sql.Connection con = connector.openConnection();
                java.sql.PreparedStatement ps = con.prepareStatement(
                    "SELECT id, name FROM users ORDER BY id ASC LIMIT 1");
                java.sql.ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    model.User u = new model.User();
                    u.setUserId(rs.getInt("id"));
                    u.setUsername(rs.getString("name"));
                    util.SessionManager.setCurrentUser(u);
                } else {
                    // No users in DB — use id=0 (will fail FK if strict; good enough for testing)
                    model.User u = new model.User();
                    u.setUserId(0);
                    u.setUsername("test_owner");
                    util.SessionManager.setCurrentUser(u);
                }
                con.close();
            } catch (Exception ex) {
                ex.printStackTrace();
                model.User u = new model.User();
                u.setUserId(0);
                u.setUsername("test_owner");
                util.SessionManager.setCurrentUser(u);
            }
        }
        HouseController controller = new HouseController();
        new Owner_Add_House(controller).setVisible(true);
    });
 }

    

