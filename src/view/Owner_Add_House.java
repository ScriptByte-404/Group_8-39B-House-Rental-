    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 
 
 
    if (jTextField2.getText().isEmpty() || jTextField3.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in house name and location.");
        return;
    }
 
    House house = new House();
    house.setName(jTextField2.getText());
    house.setLocation(jTextField3.getText());
    house.setPrice(jTextField1.getText());
    house.setType((String) cmbHouseType.getSelectedItem());
    house.setBedrooms((String) cmbBedrooms.getSelectedItem());
    house.setBathrooms((String) cmbBathrooms.getSelectedItem());
    house.setKitchens((String) cmbKitchens.getSelectedItem());
    house.setDescription(jTextArea1.getText());
 
    List<String> amenities = new ArrayList<>();
    if (wifiCheck1.isSelected()) amenities.add("WI-FI");
    if (securityCheck.isSelected()) amenities.add("24/7 security");
    if (acCheck.isSelected()) amenities.add("Air Condition");
    if (balconyCheck.isSelected()) amenities.add("Balcony");
    if (utilitiesCheck.isSelected()) amenities.add("Utilities");
    if (parkingCheck.isSelected()) amenities.add("Parking");
    house.setAmenities(amenities);
 
    house.setImages(new ArrayList<>(selectedImages));
 
    // Guard: ensure user is logged in before accessing session
    if (SessionManager.getCurrentUser() == null) {
        JOptionPane.showMessageDialog(this, "Session expired. Please log in again.", "Session Error", JOptionPane.ERROR_MESSAGE);
        new view.Login().setVisible(true);
        this.dispose();
        return;
    }
    house.setOwnerId(SessionManager.getCurrentUser().getUserId());
 
    // Set approved so house shows in Dashboard, Search, and HouseDetails immediately
    house.setStatus("approved");
 
    houseController.addHouse(house);
 
    JOptionPane.showMessageDialog(this, "House added successfully!");
 
    // Reset form for next house (so owner can add multiple)
    jTextField2.setText("");
    jTextField3.setText("");
    jTextField1.setText("");
    jTextArea1.setText("");
    cmbHouseType.setSelectedIndex(0);
    cmbBedrooms.setSelectedIndex(0);
    cmbBathrooms.setSelectedIndex(0);
    cmbKitchens.setSelectedIndex(0);
    wifiCheck1.setSelected(false);
    securityCheck.setSelected(false);
    acCheck.setSelected(false);
    balconyCheck.setSelected(false);
    utilitiesCheck.setSelected(false);
    parkingCheck.setSelected(false);
 
    selectedImages.clear();
    JLabel[] previews = {lblPreview1, lblPreview2, lblPreview3, lblPreview4};
    for (JLabel p : previews) p.setIcon(null);
 
    
    }//GEN-LAST:event_jButton1ActionPerformed

