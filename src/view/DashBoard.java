    private void Iconlogo_ButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Iconlogo_ButtonActionPerformed
        User currentUser = SessionManager.getCurrentUser();
        if (currentUser == null) {
            JOptionPane.showMessageDialog(this, "Please login to view notifications.", "Not Logged In", JOptionPane.WARNING_MESSAGE);
            return;
        }

        List<Notification> notifications = notificationDAO.getNotificationsByUserId(currentUser.getUserId());
        List<Notice> notices = noticeDAO.getAllNotices();

        JPopupMenu popup = new JPopupMenu();
        popup.setBorder(BorderFactory.createTitledBorder("Notifications"));

        // Create a scroll pane for the popup content
        JPanel contentPanel = new JPanel();
        contentPanel.setLayout(new BoxLayout(contentPanel, BoxLayout.Y_AXIS));

        if (notifications.isEmpty() && notices.isEmpty()) {
            JLabel noNotifLabel = new JLabel("No notifications");
            noNotifLabel.setEnabled(false);
            contentPanel.add(noNotifLabel);
        } else {
            // Add admin notices first
            for (Notice n : notices) {
                JButton item = new JButton("<html><b>ANNOUNCEMENT:</b> " + n.getTitle() + "<br>" + n.getMessage() +
                    (n.getCreatedAt() != null ? "<br><small>" + n.getCreatedAt() + "</small>" : "") + "</html>");
                item.setFont(item.getFont().deriveFont(java.awt.Font.BOLD));
                item.setHorizontalAlignment(SwingConstants.LEFT);
                item.setBorderPainted(false);
                item.setContentAreaFilled(false);
                item.setFocusPainted(false);
                item.setMaximumSize(new java.awt.Dimension(350, 80));
                item.addActionListener(e -> showNoticeDetail(n));
                contentPanel.add(item);
            }

            // Add separator if there are both notices and notifications
            if (!notices.isEmpty() && !notifications.isEmpty()) {
                contentPanel.add(new JSeparator());
            }

            // Add user-specific notifications
            for (Notification n : notifications) {
                JButton item = new JButton("<html>" + n.getMessage() +
                    (n.getCreatedAt() != null ? "<br><small>" + n.getCreatedAt() + "</small>" : "") + "</html>");
                if (!n.isRead()) {
                    item.setFont(item.getFont().deriveFont(java.awt.Font.BOLD));
                }
                item.setHorizontalAlignment(SwingConstants.LEFT);
                item.setBorderPainted(false);
                item.setContentAreaFilled(false);
                item.setFocusPainted(false);
                item.setMaximumSize(new java.awt.Dimension(350, 80));
                item.addActionListener(e -> showNotificationDetail(n));
                contentPanel.add(item);
            }

            if (!notifications.isEmpty()) {
                contentPanel.add(new JSeparator());
                JButton markAllRead = new JButton("Mark All as Read");
                markAllRead.addActionListener(e -> {
                    notificationDAO.markAllAsRead(currentUser.getUserId());
                    popup.setVisible(false);
                });
                contentPanel.add(markAllRead);
            }
        }

        JScrollPane scrollPane = new JScrollPane(contentPanel);
        scrollPane.setPreferredSize(new java.awt.Dimension(380, 300));
        scrollPane.setVerticalScrollBarPolicy(JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED);
        popup.add(scrollPane);

        popup.show(Iconlogo_Button, 0, Iconlogo_Button.getHeight());
    }//GEN-LAST:event_Iconlogo_ButtonActionPerformed

    private void showNoticeDetail(Notice notice) {
        JDialog dialog = new JDialog(this, "Notice Details", true);
        dialog.setSize(500, 400);
        dialog.setLayout(new BorderLayout());

        JPanel panel = new JPanel(new BorderLayout());
        panel.setBorder(BorderFactory.createEmptyBorder(20, 20, 20, 20));

        JLabel titleLabel = new JLabel("<html><h2>" + notice.getTitle() + "</h2></html>");
        JLabel messageLabel = new JLabel("<html><p>" + notice.getMessage() + "</p></html>");
        JLabel dateLabel = new JLabel("Posted: " + notice.getCreatedAt());

        JButton closeButton = new JButton("Close");
        closeButton.addActionListener(e -> dialog.dispose());

        panel.add(titleLabel, BorderLayout.NORTH);
        panel.add(messageLabel, BorderLayout.CENTER);
        panel.add(dateLabel, BorderLayout.SOUTH);

        dialog.add(panel, BorderLayout.CENTER);
        dialog.add(closeButton, BorderLayout.SOUTH);

        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }

    private void showNotificationDetail(Notification notification) {
        JDialog dialog = new JDialog(this, "Notification Details", true);
        dialog.setSize(500, 400);
        dialog.setLayout(new BorderLayout());

        JPanel panel = new JPanel(new BorderLayout());
        panel.setBorder(BorderFactory.createEmptyBorder(20, 20, 20, 20));

        JLabel messageLabel = new JLabel("<html><p>" + notification.getMessage() + "</p></html>");
        JLabel dateLabel = new JLabel("Received: " + notification.getCreatedAt());

        JButton markReadButton = new JButton("Mark as Read");
        markReadButton.addActionListener(e -> {
            notificationDAO.markAsRead(notification.getId());
            JOptionPane.showMessageDialog(dialog, "Marked as read!");
            dialog.dispose();
        });

        JButton closeButton = new JButton("Close");
        closeButton.addActionListener(e -> dialog.dispose());

        JPanel buttonPanel = new JPanel();
        buttonPanel.add(markReadButton);
        buttonPanel.add(closeButton);

        panel.add(messageLabel, BorderLayout.CENTER);
        panel.add(dateLabel, BorderLayout.SOUTH);

        dialog.add(panel, BorderLayout.CENTER);
        dialog.add(buttonPanel, BorderLayout.SOUTH);

        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }

