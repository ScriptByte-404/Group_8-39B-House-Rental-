private void loadHouses() {
    List<House> houses = houseController.getAllHouses();

    if (houses == null || houses.isEmpty()) {
        System.out.println("No houses found");
        return;
    }

    JButton[] buttons = {RecommendedHouse2_Button1, RecommendedHouse2_Button2, RecommendedHouse2_Button3};

    for (int i = 0; i < buttons.length && i < houses.size(); i++) {
        House h = houses.get(i);
        JButton btn = buttons[i];

        btn.setText("<html><center>" + h.getName() + "<br>" + h.getLocation() + "<br>" + h.getPrice() + "</center></html>");

        if (h.getImages() != null && !h.getImages().isEmpty()) {
            ImageIcon icon = new ImageIcon(h.getImages().get(0));
            if (icon.getIconWidth() > 0) { // Check if image loaded successfully
                Image scaled = icon.getImage().getScaledInstance(260, 140, Image.SCALE_SMOOTH);
                btn.setIcon(new ImageIcon(scaled));
            } else {
                // Use placeholder if image path is invalid
                ImageIcon placeholder = new ImageIcon(getClass().getResource("/images/House_Bg.png"));
                Image scaled = placeholder.getImage().getScaledInstance(260, 140, Image.SCALE_SMOOTH);
                btn.setIcon(new ImageIcon(scaled));
            }
        } else {
            // Use placeholder if no images
            ImageIcon placeholder = new ImageIcon(getClass().getResource("/images/House_Bg.png"));
            Image scaled = placeholder.getImage().getScaledInstance(260, 140, Image.SCALE_SMOOTH);
            btn.setIcon(new ImageIcon(scaled));
        }

        btn.setContentAreaFilled(false);
        btn.setFocusPainted(false);
        btn.setVerticalTextPosition(JButton.BOTTOM);
        btn.setHorizontalTextPosition(JButton.CENTER);

        // remove any old listeners by replacing with a fresh one
        for (java.awt.event.ActionListener al : btn.getActionListeners()) {
            btn.removeActionListener(al);
        }

        btn.addActionListener(e -> new HouseDetails(h).setVisible(true));
    }

    House first = houses.get(0);
    House1Name_Text.setText(first.getName());
    House1Price_Text.setText(first.getPrice());
    Location_txt.setText(first.getLocation());
}

